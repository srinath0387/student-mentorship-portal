CREATE TABLE student_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    roll_number VARCHAR(50),
    batch VARCHAR(20),
    year INTEGER,
    section VARCHAR(10),
    mobile VARCHAR(20),
    date_of_birth DATE,
    linkedin_url VARCHAR(500),
    github_url VARCHAR(500),
    github_username VARCHAR(100),
    portfolio_url VARCHAR(500),
    kaggle_url VARCHAR(500),
    leetcode_url VARCHAR(500),
    leetcode_username VARCHAR(100),
    hackerrank_url VARCHAR(500),
    codechef_url VARCHAR(500),
    codeforces_url VARCHAR(500),
    gfg_url VARCHAR(500),
    stackoverflow_url VARCHAR(500),
    medium_url VARCHAR(500),
    devto_url VARCHAR(500),
    native_place VARCHAR(200),
    address TEXT,
    hostel_or_day_scholar VARCHAR(20),
    languages_known TEXT,
    parents_occupation VARCHAR(200),
    first_graduate BOOLEAN DEFAULT FALSE,
    family_business VARCHAR(200),
    financial_background VARCHAR(50),
    preferred_career VARCHAR(200),
    dream_companies TEXT,
    higher_studies_interest BOOLEAN DEFAULT FALSE,
    startup_interest BOOLEAN DEFAULT FALSE,
    professional_interests JSONB DEFAULT '[]'::jsonb,
    current_cgpa DECIMAL(4,2),
    current_semester INTEGER,
    semester_gpas JSONB DEFAULT '[]'::jsonb,
    attendance_percentage DECIMAL(5,2),
    programming_languages JSONB DEFAULT '[]'::jsonb,
    leetcode_stats JSONB DEFAULT '{}'::jsonb,
    hackerrank_stats JSONB DEFAULT '{}'::jsonb,
    codechef_stats JSONB DEFAULT '{}'::jsonb,
    codeforces_stats JSONB DEFAULT '{}'::jsonb,
    gfg_stats JSONB DEFAULT '{}'::jsonb,
    github_stats JSONB DEFAULT '{}'::jsonb,
    resume_uploaded BOOLEAN DEFAULT FALSE,
    linkedin_updated BOOLEAN DEFAULT FALSE,
    github_updated BOOLEAN DEFAULT FALSE,
    portfolio_ready BOOLEAN DEFAULT FALSE,
    open_to_remote BOOLEAN DEFAULT FALSE,
    open_to_hybrid BOOLEAN DEFAULT FALSE,
    open_to_relocate BOOLEAN DEFAULT FALSE,
    expected_stipend VARCHAR(50),
    preferred_location VARCHAR(200),
    has_passport BOOLEAN DEFAULT FALSE,
    has_driving_license BOOLEAN DEFAULT FALSE,
    hidden_talents TEXT,
    profile_completion_percentage INTEGER DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_student_profiles_user_id ON student_profiles(user_id);
CREATE INDEX idx_student_profiles_roll_number ON student_profiles(roll_number);
CREATE INDEX idx_student_profiles_batch ON student_profiles(batch);
